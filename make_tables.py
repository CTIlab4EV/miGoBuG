"""Tables R1, R2, R4 of the response letter from ONE results folder.

    python3 make_tables.py results/final

Writes <folder>/summary_per_case.csv and letter/tables_generated.tex (LaTeX
rows to paste into the letter).  miGoBuG time = total time used for the
comparison (final continuation run + fixed-topology QP + earlier attempts of
the restart rule).  For cases that needed restarts, the total is printed as
"total (final run + restarts)".  Delta values use the driver's convention
100 (J - J_ref) / J.
"""
import csv
import statistics as st
import sys
from pathlib import Path

folder = Path(sys.argv[1] if len(sys.argv) > 1 else "results/final")
rows = list(csv.DictReader(open(folder / "main.csv")))
CONFIGS = ["I", "II", "III", "IV", "V"]


def num(r, k):
    try:
        return float(r[k])
    except (KeyError, TypeError, ValueError):
        return float("nan")


def delta(J, J_ref):
    return 100.0 * (J - J_ref) / J


def times(r):
    total = num(r, "t_total")
    restarts = num(r, "t_restart_attempts")
    restarts = 0.0 if restarts != restarts else restarts
    return total, total - restarts, restarts


def time_cell(r):
    total, final, restarts = times(r)
    if restarts > 0:
        return f"{total:.1f} ({final:.1f} + {restarts:.1f})"
    return f"{total:.1f}"


def fx(x, d):
    """Fixed-point format without a negative zero."""
    s = f"{x:.{d}f}"
    return s[1:] if s.startswith("-") and float(s) == 0 else s


def ft(x):
    """Time in seconds with a precision suited to its size."""
    return f"{x:.3f}" if x < 0.1 else f"{x:.2f}" if x < 1 else f"{x:.1f}" if x < 100 else f"{x:.0f}"


def complete(r):
    """miGoBuG costed by the fixed-topology QP and a Gurobi result present."""
    return r.get("seq_feasible") == "True" and r.get("MIQP_status") not in ("", None)


# ---------------------------------------------------------------- per case
out = []
for r in rows:
    total, final, restarts = times(r)
    out.append(dict(config=r["config"], case=r["case"], steps=r.get("steps_used"),
                    attempts=r.get("n_attempts"), eps_pi_last=r.get("eps_pi_last"),
                    t_final_run=round(final, 3), t_restarts=round(restarts, 3), t_total=round(total, 3),
                    seq_feasible=r.get("seq_feasible"), J_miGoBuG=r.get("J_miGoBuG_ZOH"),
                    MIQP_status=r.get("MIQP_status"), MIQP_time=r.get("MIQP_time"),
                    MIQP_J_inc=r.get("MIQP_J_inc"), MIQP_J_LB=r.get("MIQP_J_LB"),
                    MIQP_gap_pct=r.get("MIQP_gap_pct"), delta_inc_pct=r.get("gap_vs_inc_pct"),
                    delta_LB_pct=r.get("gap_certified_pct")))
with open(folder / "summary_per_case.csv", "w", newline="") as f:
    w = csv.DictWriter(f, list(out[0]))
    w.writeheader()
    w.writerows(out)

tex = ["% generated by make_tables.py from " + str(folder) + " -- do not edit by hand", ""]

# ---------------------------------------------------------------- Table III (letter: Response 2.3)
tex.append("% ---- Table III rows (Configuration III, per case) ----")
for r in sorted((r for r in rows if r["config"] == "III"), key=lambda r: int(r["case"])):
    if not complete(r):
        tex.append(f"{r['case']} & \\tbd{{pending}} \\\\")
        continue
    status = "optimal" if r["MIQP_status"] == "optimal" else "time limit"
    tex.append(f"{r['case']} & {status} & {num(r, 'MIQP_time'):.1f} & {num(r, 'MIQP_J_inc') / 1e6:.5f} & "
               f"{num(r, 'MIQP_J_LB') / 1e6:.5f} & {num(r, 'MIQP_gap_pct'):.3f} & "
               f"{fx(num(r, 'gap_vs_inc_pct'), 4)} & {fx(num(r, 'gap_certified_pct'), 4)} & {time_cell(r)}\\\\")
tex.append("")

# ---------------------------------------------------------------- Table VI (letter: Response 2.2)
tex.append("% ---- Table VI rows (per configuration) ----")
restarted = []
for c in CONFIGS:
    R = [r for r in rows if r["config"] == c]
    if len(R) < 10 or not all(complete(r) for r in R):
        tex.append(f"% {c}: {sum(complete(r) for r in R)}/10 cases complete -- row not written yet")
        continue
    opt = [r for r in R if r["MIQP_status"] == "optimal"]
    tm = [num(r, "MIQP_time") for r in R]
    tot = [times(r)[0] for r in R]
    d = [num(r, "gap_vs_inc_pct") for r in R]
    k = R[0]["k"]
    nbin = "--" if c == "I" else (R[0].get("MIQP_n_bin") or "--")      # Config I: no topology binaries
    trange = "3600" if min(tm) >= 3600 else f"{ft(min(tm))}--{ft(max(tm))}"
    tex.append(f"{c} & {k} & {nbin} & {len(opt)} / {10 - len(opt)} & {trange} & "
               f"{max(num(r, 'MIQP_gap_pct') for r in R):.3f} & {st.median(tot):.1f} ({max(tot):.1f}) & "
               f"{fx(st.median(d), 4)} ({fx(max(d), 4)})\\\\")
    restarted += [f"{c}-{r['case']}: {time_cell(r)}~s" for r in R if times(r)[2] > 0]
if restarted:
    tex.append("% restarted cases (total (final run + earlier runs)): " + "; ".join(restarted))
tex.append("")

# ---------------------------------------------------------------- Table IV (letter: Response 1.3)
tex.append("% ---- Table IV rows (Configuration III, MINLP vs MILP vs miGoBuG) ----")
R = [r for r in rows if r["config"] == "III"]
if len(R) == 10 and all(complete(r) for r in R):
    def line(name, J_key, t_key, ref=True):
        J = [num(r, J_key) for r in R]
        t = [num(r, t_key) for r in R]
        d = [delta(j, num(r, "MIQP_J_inc")) for j, r in zip(J, R)]
        dcell = "0 (reference)" if not ref else f"{fx(st.mean(d), 3)} ({fx(min(d), 3)} to {fx(max(d), 3)})"
        return f"{name} & {st.mean(J) / 1e7:.4f} & {dcell} & {ft(st.median(t))} ({ft(max(t))})\\\\"
    tex.append(line("MINLP (Gurobi)$^{a}$", "MIQP_J_inc", "MIQP_time", ref=False))
    for L in (8, 16, 32):
        tex.append(line(f"MILP-PWL, $L={L}$", f"PWL{L}_J_true", f"PWL{L}_time"))
    for L in (16, 32):
        tex.append(line(f"MILP-PWL, $L={L}$, sequence + QP$^{{b}}$", f"PWL{L}_J_seqQP", f"PWL{L}_time_seqQP"))
    J = [num(r, "J_miGoBuG_ZOH") for r in R]
    d = [num(r, "gap_vs_inc_pct") for r in R]
    tot = [times(r)[0] for r in R]
    tex.append(f"\\ZOH{{}} (continuation + QP$^{{b}}$) & {st.mean(J) / 1e7:.4f} & "
               f"{fx(st.mean(d), 3)} ({fx(min(d), 3)} to {fx(max(d), 3)}) & {ft(st.median(tot))} ({ft(max(tot))})\\\\")
    opt = sum(r["MIQP_status"] == "optimal" for r in R)
    tex.append(f"% footnote a: optimality proven in {opt} of 10 cases; 3600 s limit reached in {10 - opt}.")
else:
    tex.append("% Configuration III not complete yet")

Path("letter").mkdir(exist_ok=True)
Path("letter/tables_generated.tex").write_text("\n".join(tex) + "\n")
print("\n".join(tex))
print(f"\nwrote {folder / 'summary_per_case.csv'} and letter/tables_generated.tex")

# ---------------------------------------------------------------- Table III, per dataset (all configurations)
# one row per dataset; for Configurations II-V: Gurobi (time to proven optimality, or
# final gap with a dagger if stopped at 3600 s), Delta_inc of miGoBuG, miGoBuG time
tex2 = ["% ---- Table III rows (per dataset, Configurations II-V) ----"]
by = {(r["config"], int(r["case"])): r for r in rows}
for i in range(1, 11):
    cells = [str(i)]
    for c in ("II", "III", "IV", "V"):
        r = by.get((c, i))
        if r is None or not complete(r):
            cells += ["\\tbd{}"] * 3
            continue
        g = (ft(num(r, "MIQP_time")) if r["MIQP_status"] == "optimal"
             else f"{num(r, 'MIQP_gap_pct'):.2f}$^\\dagger$")
        cells += [g, fx(num(r, "gap_vs_inc_pct"), 3), f"{times(r)[0]:.1f}"]
    tex2.append(" & ".join(cells) + "\\\\")
Path("letter/tables_generated.tex").write_text(Path("letter/tables_generated.tex").read_text() + "\n".join(tex2) + "\n")
print("\n".join(tex2))
